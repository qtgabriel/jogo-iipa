FLOOR, WALL, EXIT, SPAWN = 0, 1, 98, 99

COLORS = {FLOOR: (1, 0, 0), SPAWN: (1, 0, 0), WALL: (0, 0, 0), EXIT: (1, 0.85, 0)}


class WorldMap:

    def __init__(self, screen, sqr_size, map_data=MAP_1):
        self.screen = screen
        self.sqr_size = sqr_size
        self.map = map_data
        self.origin = (-len(map_data[0]) * sqr_size / 2, len(map_data) * sqr_size / 2)

    def _find(self, mark):
        for row, cells in enumerate(self.map):
            if mark in cells:
                return row, cells.index(mark)
        return None

    def spawn(self):
        return self._find(SPAWN)

    def exit(self):
        return self._find(EXIT)

    def draw(self):
        tracing = self.screen.tracer()
        self.screen.tracer(0)

        t = turtle.Turtle()
        t.hideturtle()
        t.speed(0)
        for row, cells in enumerate(self.map):
            for col, cell in enumerate(cells):
                x = self.origin[0] + col * self.sqr_size
                y = self.origin[1] - row * self.sqr_size
                self._square(t, x, y, COLORS.get(cell, (1, 1, 1)))

        self.screen.update()
        self.screen.tracer(tracing)

    def _square(self, t, x, y, color):
        t.penup()
        t.goto(x, y)
        t.pendown()
        t.color(color)
        t.begin_fill()
        for _ in range(4):
            t.forward(self.sqr_size)
            t.right(90)
        t.end_fill()

    def cell_to_pixel(self, row, col):
        x = self.origin[0] + col * self.sqr_size + self.sqr_size / 2
        y = self.origin[1] - row * self.sqr_size - self.sqr_size / 2
        return x, y

    def is_walkable(self, row, col):
        if not (0 <= row < len(self.map) and 0 <= col < len(self.map[row])):
            return False
        return self.map[row][col] in (FLOOR, EXIT, SPAWN)
