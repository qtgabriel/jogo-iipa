    @property
    def pixel_width(self) -> int:
        return len(self.map[0]) * self.sqr_size

    @property
    def pixel_height(self) -> int:
        return len(self.map) * self.sqr_size

    @property
    def spawn(self) -> tuple[int, int]:
        """Célula marcada com 99, onde o jogador começa."""
        for row, cells in enumerate(self.map):
            if 99 in cells:
                return row, cells.index(99)
        raise ValueError("o mapa precisa de um 99 marcando o spawn")

    def draw(self) -> None:
        tracing = self.screen.tracer()
        self.screen.tracer(0)

        t = turtle.Turtle()
        t.hideturtle()
        t.speed(0)
        x1 = self.origin[0]
        y1 = self.origin[1]
        t.up()
        t.goto(x1, y1)
        t.down()
        for index, row in enumerate(self.map):
            for col in row:
                if col in (0, 99):
                    self._d_square(t, self.sqr_size, (1,0,0))
                elif col == 1:
                    self._d_square(t, self.sqr_size, (0,0,0))
                else:
                    self._d_square(t, self.sqr_size, (1,1,1))
            t.up()
            t.goto(x1, y1 - (index + 1) * self.sqr_size)
            t.down()

        self.screen.update()
        self.screen.tracer(tracing)

    def cell_to_pixel(self, row: int, col: int) -> tuple[float, float]:
        x = self.origin[0] + col * self.sqr_size + self.sqr_size / 2
        y = self.origin[1] - row * self.sqr_size - self.sqr_size / 2
        return x, y

    def is_walkable(self, row: int, col: int) -> bool:
        if not (0 <= row < len(self.map) and 0 <= col < len(self.map[row])):
            return False
        return self.map[row][col] in self.passable

    def _d_square(self, t: turtle.Turtle, l: int, color: tuple) -> None:
        t.color(color)
        t.begin_fill()
        for _ in range(4):
            t.forward(l)
            t.right(90)
        t.end_fill()
        t.forward(l)
